/** جملهٔ واکنش: اگر برای این بازی فهرست مخصوص هست آن، وگرنه عمومی. رکورد همیشه عمومی است. */
export function reactionLines(tier: Tier, gameId?: string): string[] {
  if (tier === 'record') return TIER_LINES.record
  return (gameId && GAME_LINES[gameId]?.[tier]) || TIER_LINES[tier]
}

